/** The platform a URL belongs to. mailto: and bare addresses are Email; anything unknown is a Website. */
export function socialKindOf(href: string): SocialKind {
  const raw = href.trim();
  if (/^mailto:/i.test(raw)) return "email";
  if (/^[^\s@/:]+@[^\s@/:]+\.[^\s@/:]+$/.test(raw)) return "email";
  let host = "";
  try {
    host = new URL(/^[a-z][a-z0-9+.-]*:/i.test(raw) ? raw : `https://${raw}`).hostname.toLowerCase();
  } catch {
    return "site";
  }
  host = host.replace(/\.$/, "");
  for (const [kind, domains] of DOMAINS) if (domains.some((d) => host === d || host.endsWith(`.${d}`))) return kind;
  return "site";
}

